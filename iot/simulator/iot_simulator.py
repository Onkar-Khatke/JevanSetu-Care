#!/usr/bin/env python3
"""
JeevanSetu AI - IoT Biometric Telemetry Simulator
==================================================
Simulates health sensor readings (Heart Rate, SpO2, Temperature, Blood Pressure)
and transmits them to the Spring Boot ingestion endpoint (/api/iot/readings)
with X-Device-Key security header authentication.

All packets generated by this simulator are explicitly tagged with:
  "simulated": true,
  "source": "SIMULATOR"
to prevent confusing simulated development data with real clinical hardware data.
"""

import argparse
import json
import random
import time
import urllib.request
import urllib.error

PRESETS = {
    "NORMAL": {
        "heartRate": (68, 78),
        "spo2": (97.5, 99.2),
        "temperature": (98.0, 98.6),
        "systolic": (115, 122),
        "diastolic": (74, 82),
        "respiratoryRate": (14, 18),
        "ecgSummary": "Normal Sinus Rhythm",
    },
    "MEDIUM": {
        "heartRate": (95, 105),
        "spo2": (93.0, 95.0),
        "temperature": (100.2, 101.4),
        "systolic": (135, 145),
        "diastolic": (88, 94),
        "respiratoryRate": (20, 24),
        "ecgSummary": "Mild Sinus Tachycardia",
    },
    "HIGH": {
        "heartRate": (118, 135),
        "spo2": (86.0, 89.5),
        "temperature": (101.5, 103.0),
        "systolic": (160, 180),
        "diastolic": (98, 110),
        "respiratoryRate": (26, 32),
        "ecgSummary": "Marked Tachycardia / Acute Strain",
    },
}

def generate_payload(patient_id, preset_name, device_id="SIM-DEV-NODE-01"):
    profile = PRESETS.get(preset_name, PRESETS["NORMAL"])

    hr = random.randint(*profile["heartRate"])
    spo2 = round(random.uniform(*profile["spo2"]), 1)
    temp = round(random.uniform(*profile["temperature"]), 1)
    sys = random.randint(*profile["systolic"])
    dia = random.randint(*profile["diastolic"])
    rr = random.randint(*profile["respiratoryRate"])
    ecg = profile["ecgSummary"]

    payload = {
        "patientId": patient_id,
        "deviceId": device_id,
        "heartRate": hr,
        "spo2": spo2,
        "temperature": temp,
        "systolic": sys,
        "diastolic": dia,
        "respiratoryRate": rr,
        "ecgSummary": ecg,
        "source": "SIMULATOR",
        "simulated": True,
    }
    return payload

def send_telemetry(url, device_key, payload):
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={
            "Content-Type": "application/json",
            "X-Device-Key": device_key,
        },
        method="POST"
    )

    try:
        with urllib.request.urlopen(req, timeout=5) as resp:
            status = resp.status
            body = resp.read().decode("utf-8")
            return status, json.loads(body)
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8")
        return e.code, json.loads(body) if body else {"error": str(e)}
    except Exception as e:
        return 0, {"error": str(e)}

def main():
    parser = argparse.ArgumentParser(description="JeevanSetu IoT Telemetry Simulator")
    parser.add_argument("--patient", default="P1001", help="Target Patient ID (default: P1001)")
    parser.add_argument("--preset", choices=["NORMAL", "MEDIUM", "HIGH"], default="HIGH", help="Biometric preset")
    parser.add_argument("--url", default="http://localhost:8080/api/iot/readings", help="Backend IoT ingestion URL")
    parser.add_argument("--key", default="jeevansetu-iot-secure-dev-key-2026", help="X-Device-Key header secret")
    parser.add_argument("--stream", action="store_true", help="Continuously stream vitals")
    parser.add_argument("--interval", type=int, default=5, help="Interval in seconds for streaming mode")
    parser.add_argument("--count", type=int, default=1, help="Count of single-shot packets (default: 1)")

    args = parser.parse_args()

    print("=" * 65)
    print("  JeevanSetu AI - IoT Biometric Sensor Simulator")
    print("=" * 65)
    print(f"Target Patient : {args.patient}")
    print(f"Preset Profile : {args.preset}")
    print(f"Ingestion URL  : {args.url}")
    print(f"Security Header: X-Device-Key configured")
    print(f"Simulation Tag : simulated=True (Strictly separated from hardware)")
    print("=" * 65)

    if args.stream:
        print(f"Starting continuous telemetry stream every {args.interval}s. Press Ctrl+C to stop.\n")
        try:
            seq = 1
            while True:
                payload = generate_payload(args.patient, args.preset)
                code, res = send_telemetry(args.url, args.key, payload)
                print(f"[#{seq}] Ingested HR={payload['heartRate']} bpm, SpO2={payload['spo2']}%, BP={payload['systolic']}/{payload['diastolic']} -> HTTP {code}")
                seq += 1
                time.sleep(args.interval)
        except KeyboardInterrupt:
            print("\nSimulation stream stopped.")
    else:
        for i in range(args.count):
            payload = generate_payload(args.patient, args.preset)
            code, res = send_telemetry(args.url, args.key, payload)
            print(f"[Packet {i+1}] Sent: HR={payload['heartRate']} bpm, SpO2={payload['spo2']}%, BP={payload['systolic']}/{payload['diastolic']} mmHg, Temp={payload['temperature']}°F")
            print(f"Response (HTTP {code}): {json.dumps(res, indent=2)}")

if __name__ == "__main__":
    main()
